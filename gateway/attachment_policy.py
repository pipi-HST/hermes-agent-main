"""Turn-scoped local file grants for gateway agent replies."""

from contextlib import contextmanager
from contextvars import ContextVar
from dataclasses import dataclass
from pathlib import Path
import re
import stat


@dataclass(frozen=True)
class LocalAttachment:
    path: Path
    identity: tuple[int, int, int, int, int]
    is_voice: bool = False

    @staticmethod
    def file_identity(path: Path) -> tuple[int, int, int, int, int] | None:
        try:
            if not path.is_absolute() or path.resolve(strict=True) != path:
                return None
            info = path.stat()
        except (OSError, RuntimeError, ValueError):
            return None
        if not stat.S_ISREG(info.st_mode):
            return None
        return (info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns, info.st_ctime_ns)

    def is_current(self) -> bool:
        return self.file_identity(self.path) == self.identity


class AgentReply(str):
    """Text plus out-of-band local media; reply text itself cannot grant delivery."""

    def __new__(cls, text: str, attachments: tuple[LocalAttachment, ...] = ()):
        reply = super().__new__(cls, text)
        reply.attachments = attachments
        return reply

    def local_media(self) -> list[tuple[str, bool]]:
        return [(str(item.path), item.is_voice) for item in self.attachments if item.is_current()]


@dataclass
class _Turn:
    wants_export: bool
    attachments: dict[Path, LocalAttachment]


_TURN: ContextVar[_Turn | None] = ContextVar("gateway_attachment_turn", default=None)

# Only accept standalone requests in raw user text, not quoted text, history,
# or the prompt after enrichment with attachments and other content.
_EXPORT_REQUEST = re.compile(
    r"(?:"
    r"(?:please )?(?:export (?:it|this|the (?:draft|answer|report))(?: as (?:a |an )?(?:file|markdown))?"
    r"|(?:send|attach) (?:me )?(?:the |a )?(?:file|report|markdown file))"
    r"|(?:请)?(?:导出(?:成|为)?(?:文件|Markdown|全文|(?:这|该|当前)(?:份)?(?:草稿|回答|报告))?"
    r"|(?:把)?(?:这份|当前|上一条)?(?:草稿|回答|报告|全文)?(?:以|用|作为)?(?:文件|附件)(?:的形式)?发给我"
    r"|发(?:个|一份)?(?:文件|附件)(?:给我)?|发给我(?:文件|附件)|给我(?:一份|个)?(?:文件|附件))"
    r")[.!。！]?",
    re.IGNORECASE,
)


@contextmanager
def collect_local_attachments(user_text: str = ""):
    turn = _Turn(bool(_EXPORT_REQUEST.fullmatch(user_text.strip())), {})
    token = _TURN.set(turn)
    try:
        yield turn.attachments
    finally:
        _TURN.reset(token)


def _register(turn: _Turn, path: Path, *, is_voice: bool = False) -> None:
    identity = LocalAttachment.file_identity(path)
    if identity is not None and len(turn.attachments) < 16:
        turn.attachments[path] = LocalAttachment(path, identity, is_voice)


def register_generated_audio(file_path: str, *, is_voice: bool) -> None:
    """Register audio just generated by the local TTS provider."""
    turn = _TURN.get()
    if turn is not None:
        path = Path(file_path)
        if path.suffix.lower() in {".mp3", ".wav", ".ogg", ".opus", ".m4a", ".flac"}:
            _register(turn, path, is_voice=is_voice)


_EXPORT_PRODUCERS = {
    ("capture_bridge", "show_capture_draft"): ("as_file", "capture_draft_fulltext", "capture"),
    ("rag_bridge", "search_knowledge_base"): ("export_file", "rag_answer_report", "rag"),
    ("rag_continue_bridge", "continue_latest_rag_answer"): ("export_file", "rag_answer_report", "rag"),
    ("garden_bridge", "synthesize_garden"): ("export_file", "garden_draft_report", "garden"),
    ("librarian_bridge", "run_librarian_audit"): ("export_file", "librarian_markdown_report", "library"),
    ("theme_bridge", "run_theme_scan"): ("export_file", "theme_scan_report", "theme"),
}


def register_knowledge_exports(
    root: Path, module: str, function: str, kwargs: dict, result: object
) -> None:
    """Record supported export files from a successful local bridge call."""
    turn = _TURN.get()
    producer = _EXPORT_PRODUCERS.get((module, function))
    if turn is None or not turn.wants_export or producer is None:
        return
    flag, kind, folder = producer
    if kwargs.get(flag) is not True or not isinstance(result, dict) or result.get("status") != "success":
        return
    artifacts = result.get("durable_artifacts")
    if not isinstance(artifacts, list):
        return
    try:
        export_dir = root.resolve(strict=True) / "data" / "exports" / folder
        if export_dir.resolve(strict=True) != export_dir:
            return
    except (OSError, RuntimeError, ValueError):
        return
    for artifact in artifacts:
        if not isinstance(artifact, dict) or artifact.get("type") != kind or artifact.get("status") != "created":
            continue
        value = artifact.get("path")
        if isinstance(value, str):
            path = Path(value)
            if path.parent == export_dir and path.suffix.lower() == ".md":
                _register(turn, path)
